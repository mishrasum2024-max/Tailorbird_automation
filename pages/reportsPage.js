const fs = require("fs");
const os = require("os");
const path = require("path");
const pdfParse = require("pdf-parse");
const { expect } = require("@playwright/test");
const { Logger } = require("../utils/logger");
const { reportsLocators } = require("../locators/reportsLocator");
const { ReportPage } = require("./reportPage");

/**
 * Page object for Reports: generate an AI report through the report assistant and export it.
 * Used by the FEAT-1313 worker-thread PDF cases (PDF / Excel export must still produce valid files).
 */
class ReportsPage {
  constructor(page) {
    this.page = page;
    this.loc = reportsLocators(page);
  }

  async goToNewReport() {
    await this.page.goto("/reports/new", { waitUntil: "load" });
    await expect(
      this.loc.chatInput,
      "Report assistant input must be visible"
    ).toBeVisible({ timeout: 60000 });
  }

  async goToReportsHome() {
    await this.page.goto("/reports", { waitUntil: "load" });
    await expect(this.page).toHaveURL(/\/reports$/);
  }

  /** Describes a report to the assistant and waits for the generated report preview. */
  async generateReport(prompt) {
    await this.goToNewReport();
    await this.loc.chatInput.fill(prompt);
    await this.page.keyboard.press("Enter");
    await expect(this.page, "Report must be created").toHaveURL(
      /\/reports\/\d+/,
      { timeout: 180000 }
    );
    await expect(
      this.loc.generatedMarker,
      "Generated report must finish"
    ).toBeVisible({ timeout: 180000 });
    const reportUrl = this.page.url();
    Logger.success(`Report generated: ${reportUrl}`);
    return reportUrl;
  }

  /**
   * Reuses a report instead of generating one each run, through the same path a user takes:
   * Dashboard → "Reports" in the left panel → search the report's name → View report. The report
   * is the newest one generated from `prompt` (e.g. the invoice report for the invoice prompt)
   * that can still be exported: its file loads and the Reports search still lists it. Only when no
   * such report exists (none was ever made, or it was cleaned up) is one generated — from the same
   * Reports page via "Generate Report" — and that report is then reused by later runs.
   * Returns the report URL, like generateReport().
   * MCP-verified 2026-10-29 on beta (owner): GET /api/reports?counts=1 lists reports with
   * latestVersion { id, prompt, htmlFileUploadId }; the file is GET /api/file-upload/<id>/download
   * (200 text/html); Dashboard → Reports → search "Draws with Invoices by Property" → View report
   * opened report 718 with "Generated by", its h1 and Export (Export PDF / Export data (Excel)).
   */
  async getOrGenerateReport(prompt) {
    const ui = new ReportPage(this.page);
    const res = await this.page.request.get("/api/reports?counts=1");
    expect(res.status(), "FAIL: GET /api/reports did not return 200").toBe(200);
    const candidates = ((await res.json()).reports || [])
      .filter(
        r =>
          r.latestVersion &&
          r.latestVersion.prompt === prompt &&
          r.latestVersion.htmlFileUploadId
      )
      .sort((a, b) => b.id - a.id)
      .slice(0, 3);
    let onReportsPage = false;
    for (const candidate of candidates) {
      const file = await this.page.request.get(
        `/api/file-upload/${candidate.latestVersion.htmlFileUploadId}/download`
      );
      if (file.status() !== 200) {
        Logger.info(
          `Report ${candidate.id} file is not available (${file.status()}) — trying the next one`
        );
        continue;
      }
      if (!onReportsPage) {
        await ui.gotoDashboard();
        await ui.openReportsFromLeftPanel();
        onReportsPage = true;
      }
      const found = await ui.searchReports(candidate.name);
      if (!found.versions.some(v => v.reportId === candidate.id)) {
        Logger.info(
          `Report ${candidate.id} "${candidate.name}" is not listed by the Reports search — trying the next one`
        );
        continue;
      }
      Logger.info(`Reusing existing report ${candidate.id}: ${candidate.name}`);
      await this.viewReportFromCard(ui, candidate.id);
      return this.page.url();
    }
    Logger.info(
      `No existing report available for "${prompt}" — generating one from the Reports page`
    );
    if (!onReportsPage) {
      await ui.gotoDashboard();
      await ui.openReportsFromLeftPanel();
    }
    await ui.clickGenerateReport();
    // Same steps as generateReport() after its page.goto — they work for PDF and Excel prompts
    // (generateReportFromChat waits for an <h1>, which an Excel report never has).
    await ui.chatInput.fill(prompt);
    await ui.chatInput.press("Enter");
    await expect(this.page, "Report must be created").toHaveURL(
      /\/reports\/\d+/,
      { timeout: 180000 }
    );
    await expect(
      this.loc.generatedMarker,
      "Generated report must finish"
    ).toBeVisible({ timeout: 180000 });
    return this.page.url();
  }

  /**
   * Clicks "View report" on the report's card (Reports page). Same checks as
   * ReportPage.openOwnReportFromCard (view API 200, report URL), but "rendered" also accepts an
   * Excel report: its preview is one workbook table with no <h1> (MCP-verified 2026-10-29:
   * Excel reports 713/720/698/399 have 0 h1 + a table; PDF reports 711/718 have an h1).
   */
  async viewReportFromCard(ui, reportId) {
    const card = ui.reportCardById(this.page.getByRole("main"), reportId);
    await expect(card, `FAIL: Report ${reportId} card not listed`).toBeVisible({
      timeout: 60000,
    });
    const [apiResponse] = await Promise.all([
      this.page.waitForResponse(
        r =>
          r.url().includes(`/api/reports/${reportId}?`) &&
          r.request().method() === "GET",
        { timeout: 60000 }
      ),
      this.page.waitForURL(
        u =>
          u.pathname === `/reports/${reportId}` &&
          u.searchParams.has("versionId"),
        { timeout: 60000 }
      ),
      ui.viewLink(card).click(),
    ]);
    expect(
      apiResponse.status(),
      `FAIL: Report ${reportId} API did not return 200 on view`
    ).toBe(200);
    await expect(this.loc.generatedMarker, "Report must open").toBeVisible({
      timeout: 90000,
    });
    await expect(
      ui.reportFrame().locator("h1, table").first(),
      "FAIL: Viewed report did not render"
    ).toBeVisible({ timeout: 60000 });
    Logger.success(`View opened report ${reportId}`);
  }

  async openReport(reportUrl) {
    await this.page.goto(reportUrl, { waitUntil: "load" });
    await expect(this.loc.generatedMarker, "Report must open").toBeVisible({
      timeout: 90000,
    });
  }

  async openExportMenu() {
    await expect(this.loc.exportButton).toBeVisible({ timeout: 60000 });
    await this.loc.exportButton.click();
  }

  async getExportMenuLabels() {
    await this.openExportMenu();
    await expect(this.loc.menuItems.first()).toBeVisible();
    const labels = (await this.loc.menuItems.allInnerTexts()).map(t =>
      t.trim()
    );
    await this.page.keyboard.press("Escape");
    return labels;
  }

  /** Starts an export without waiting for the download (for navigate-away scenarios). */
  async startExportPdf() {
    await this.openExportMenu();
    await this.loc.exportPdfItem.click();
  }

  async saveDownload(download) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "feat1313-"));
    const target = path.join(
      dir,
      download.suggestedFilename().replace(/[^\w.\- ]/g, "_")
    );
    await download.saveAs(target);
    return {
      filename: download.suggestedFilename(),
      buffer: fs.readFileSync(target),
    };
  }

  async exportVia(menuItemLocator) {
    await this.openExportMenu();
    const [download] = await Promise.all([
      this.page.waitForEvent("download", { timeout: 180000 }),
      menuItemLocator.click(),
    ]);
    return this.saveDownload(download);
  }

  /** Export PDF; asserts the file is a parsable PDF and returns its text and page count. */
  async exportPdfAndRead() {
    const { filename, buffer } = await this.exportVia(this.loc.exportPdfItem);
    expect(filename, "FAIL: exported file must be a PDF").toContain(".pdf");
    expect(buffer.slice(0, 4).toString(), "FAIL: PDF header missing").toBe(
      "%PDF"
    );
    const parsed = await pdfParse(buffer);
    expect(parsed.numpages, "FAIL: PDF must have pages").toBeGreaterThan(0);
    return { filename, buffer, numpages: parsed.numpages, text: parsed.text };
  }

  async exportDataExcel() {
    return this.assertXlsx(await this.exportVia(this.loc.exportDataExcelItem));
  }

  async exportExcel() {
    return this.assertXlsx(await this.exportVia(this.loc.exportExcelItem));
  }

  assertXlsx({ filename, buffer }) {
    expect(filename, "FAIL: exported file must be .xlsx").toContain(".xlsx");
    expect(
      buffer.slice(0, 2).toString(),
      "FAIL: xlsx must be a zip container (PK)"
    ).toBe("PK");
    expect(buffer.length, "FAIL: xlsx must not be empty").toBeGreaterThan(1000);
    return { filename, buffer };
  }
}

module.exports = { ReportsPage };
