/**
 * Locators for the Reports module (beta.tailorbird.com/reports, /reports/new, /reports/:id).
 *
 * MCP-verified 2026-10-23 (owner session, headed MCP browser):
 * - Left-panel "Reports" item is an <a class="mantine-NavLink-root"> WITHOUT an href, so it has
 *   no link role — matched by its exact label (same shape as leftPanelLocator.leftPanelItem).
 * - Landing page: breadcrumb "Home / Reports", h3 "Generate a Report", "Use a Template" and
 *   "Generate Report" buttons, search textbox, and three blocks labelled "Continue",
 *   "Explore by Module" and "Recent Reports" (CSS-uppercased; DOM text is title case).
 * - Report cards (Recent Reports, Draft reports drawer, module drawers) are Mantine Papers
 *   (data-with-border) with no role of their own; each holds a "View report" link
 *   (href /reports/:id?versionId=:vid), a "Delete report" button and a DRAFT/READY badge.
 * - Drawers are dialogs named "Draft reports" / "<Module> reports"; delete confirmation is a
 *   dialog named "Delete report?"; the template picker is a dialog named "Use a Template".
 * - Report viewer: right panel with "Generated by <name> · <date>", status tag, "Regenerate",
 *   "Save as Template", "Export" (menu: "Export PDF", "Export data (Excel)") and the report
 *   rendered in a blob: iframe titled with the report name.
 *
 * Every element is a healingLocator([...]) strategy list (utils/locatorHealer.js): element-based
 * Playwright methods first, CSS only as a last-resort fallback for role-less containers.
 */
const { leftPanelItem } = require('./leftPanelLocator');

function reportsNavItemStrategies(page, label) {
    const nav = page.getByRole('navigation');
    return [
        { name: 'nav a >> text(exact)', locator: nav.locator('a').filter({ has: page.getByText(label, { exact: true }) }).first() },
        { name: 'leftPanelLocator.leftPanelItem', locator: page.locator(leftPanelItem(label)).first() },
    ];
}

function breadcrumbHomeStrategies(page) {
    const main = page.getByRole('main');
    return [
        { name: 'role:link Home', locator: main.getByRole('link', { name: 'Home', exact: true }) },
        { name: 'main a[href="/"]', locator: main.locator('a[href="/"]').filter({ has: page.getByText('Home', { exact: true }) }) },
    ];
}

function breadcrumbCurrentStrategies(page, text) {
    const main = page.getByRole('main');
    return [
        { name: 'main text(exact) first', locator: main.getByText(text, { exact: true }).first() },
        { name: 'main p text(exact) first', locator: main.locator('p').filter({ hasText: text }).first() },
    ];
}

function headingStrategies(page, name) {
    return [
        { name: 'role:heading', locator: page.getByRole('heading', { name, exact: true }) },
        { name: 'text(exact)', locator: page.getByRole('main').getByText(name, { exact: true }) },
    ];
}

function textStrategies(page, text) {
    const main = page.getByRole('main');
    return [
        { name: 'main text(exact)', locator: main.getByText(text, { exact: true }) },
        { name: 'main p filter', locator: main.locator('p').filter({ hasText: text }) },
    ];
}

function buttonStrategies(scope, name) {
    return [
        { name: 'role:button', locator: scope.getByRole('button', { name, exact: true }) },
        { name: 'button >> text(exact)', locator: scope.locator('button').filter({ has: scope.getByText(name, { exact: true }) }) },
    ];
}

function searchInputStrategies(page, placeholder) {
    return [
        { name: 'role:textbox', locator: page.getByRole('textbox', { name: placeholder }) },
        { name: 'placeholder', locator: page.getByPlaceholder(placeholder) },
    ];
}

/** Continue-block tiles: buttons whose accessible name starts with the tile title, e.g. "Draft Reports <latest name> 82". */
function continueTileStrategies(page, title) {
    const main = page.getByRole('main');
    return [
        { name: 'role:button name contains', locator: main.getByRole('button', { name: title }) },
        { name: 'button >> text(exact)', locator: main.locator('button').filter({ has: page.getByText(title, { exact: true }) }) },
    ];
}

/** Explore-by-Module tile: a role-less-name button holding "<Label>" and "<n> version(s)". */
function moduleTileStrategies(page, label) {
    const main = page.getByRole('main');
    return [
        { name: 'role:button has text(exact) + version', locator: main.getByRole('button').filter({ has: page.getByText(label, { exact: true }) }).filter({ hasText: 'version' }) },
        { name: 'main button has text(exact) + version', locator: main.locator('button').filter({ has: page.getByText(label, { exact: true }) }).filter({ hasText: 'version' }) },
    ];
}

/** All Explore-by-Module tiles (every one shows a "<n> version(s)" count). */
function moduleTilesStrategies(page) {
    const main = page.getByRole('main');
    return [
        { name: 'role:button has version count', locator: main.getByRole('button').filter({ hasText: 'version' }) },
        { name: 'main button has version count', locator: main.locator('button').filter({ hasText: 'version' }) },
    ];
}

/** Report cards inside `scope` (main page or a drawer): the bordered Paper holding a "View report" link. */
function reportCardsStrategies(page, scope) {
    const viewLink = page.getByRole('link', { name: 'View report' });
    return [
        { name: 'css:[data-with-border] has View report', locator: scope.locator('[data-with-border="true"]').filter({ has: viewLink }) },
        { name: 'css:.mantine-Paper-root has View report', locator: scope.locator('.mantine-Paper-root').filter({ has: viewLink }) },
    ];
}

/** One specific report's card inside `scope`, keyed by the report id in its View link href. */
function reportCardByIdStrategies(page, scope, reportId) {
    const hrefLink = page.locator(`a[href^="/reports/${reportId}?"]`);
    return [
        { name: 'css:[data-with-border] has href', locator: scope.locator('[data-with-border="true"]').filter({ has: page.getByRole('link', { name: 'View report' }) }).filter({ has: hrefLink }) },
        { name: 'css:.mantine-Paper-root has href', locator: scope.locator('.mantine-Paper-root').filter({ has: page.getByRole('link', { name: 'View report' }) }).filter({ has: hrefLink }) },
    ];
}

function viewReportLinkStrategies(scope) {
    return [
        { name: 'role:link View report', locator: scope.getByRole('link', { name: 'View report', exact: true }) },
        { name: 'aria-label View report', locator: scope.getByLabel('View report', { exact: true }) },
    ];
}

function deleteReportButtonStrategies(scope) {
    return [
        { name: 'role:button Delete report', locator: scope.getByRole('button', { name: 'Delete report', exact: true }) },
        { name: 'aria-label Delete report', locator: scope.getByLabel('Delete report', { exact: true }) },
    ];
}

function tagStrategies(scope, tag) {
    return [
        { name: 'text(exact)', locator: scope.getByText(tag, { exact: true }) },
        // Same node as getByText: the badge text lives in its inner label span, not the Badge root
        // (MCP-verified — a Badge-root fallback would double every count).
        { name: 'css:.mantine-Badge-label text', locator: scope.locator('.mantine-Badge-label').filter({ hasText: tag }) },
    ];
}

function dialogStrategies(page, name) {
    return [
        { name: 'role:dialog name', locator: page.getByRole('dialog', { name, exact: true }) },
        { name: 'role:dialog has heading', locator: page.getByRole('dialog').filter({ has: page.getByRole('heading', { name, exact: true }) }) },
    ];
}

function dialogCloseButtonStrategies(dialog) {
    return [
        { name: 'banner button', locator: dialog.getByRole('banner').getByRole('button') },
        { name: 'css:.mantine-Modal-close', locator: dialog.locator('.mantine-Modal-close, .mantine-Drawer-close') },
    ];
}

/** Template cards inside the "Use a Template" modal (bordered Papers in the modal body). */
function templateCardsStrategies(dialog) {
    return [
        { name: 'css:[data-with-border]', locator: dialog.locator('[data-with-border="true"]') },
        { name: 'css:.mantine-Modal-body .mantine-Paper-root', locator: dialog.locator('.mantine-Modal-body .mantine-Paper-root') },
    ];
}

function chatInputStrategies(page, name) {
    return [
        { name: 'role:textbox', locator: page.getByRole('textbox', { name, exact: true }) },
        { name: 'placeholder', locator: page.getByPlaceholder(name) },
    ];
}

function generatedByStrategies(page, prefix) {
    const main = page.getByRole('main');
    return [
        { name: 'main text contains', locator: main.getByText(prefix) },
        { name: 'main p filter', locator: main.locator('p').filter({ hasText: prefix }) },
    ];
}

function reportVersionStrategies(page) {
    return [
        { name: 'role:textbox Report version', locator: page.getByRole('textbox', { name: 'Report version', exact: true }) },
        { name: 'label Report version', locator: page.getByLabel('Report version', { exact: true }) },
    ];
}

function exportMenuItemStrategies(page, name) {
    return [
        { name: 'role:menuitem', locator: page.getByRole('menuitem', { name, exact: true }) },
        // Same node as the role strategy (a text-span fallback would be a 2nd node → strict-mode error).
        { name: 'css:[role=menuitem] has text(exact)', locator: page.locator('[role="menuitem"]').filter({ has: page.getByText(name, { exact: true }) }) },
    ];
}

/** The rendered report: a blob: iframe in main, titled with the report name. */
function reportIframeStrategies(page) {
    const main = page.getByRole('main');
    return [
        { name: 'main iframe[title]', locator: main.locator('iframe[title]') },
        { name: 'main iframe', locator: main.locator('iframe') },
    ];
}

