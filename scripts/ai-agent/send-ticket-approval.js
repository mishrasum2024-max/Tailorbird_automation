require("dotenv").config();

const { WebClient } = require("@slack/web-api");
const fs = require("fs");
const path = require("path");

const slack = new WebClient(process.env.SLACK_BOT_TOKEN);

const CHANNEL_ID = process.env.SLACK_CHANNEL_ID;

/*
 * Repository this ticket was posted from ("owner/repo").
 *
 * Stamped onto the radio option value so the shared Slack
 * listener (which serves more than one repo's messages) can
 * dispatch the next workflow to the correct repository.
 */
const GH_REPO_FULL = process.env.GH_REPO_FULL || "";

const TICKETS_FILE = path.join(
  __dirname,
  "..",
  "..",
  "data",
  "notion-completed-tickets.json"
);

/*
 * Slack radio_buttons elements support a maximum of
 * 10 options. MAX_TICKETS (get-notion-tickets.js) defaults to
 * exactly this value, but this guards against that value being
 * raised further later without updating this file.
 */
const MAX_RADIO_OPTIONS = 10;

function getShortSlackText(text, maxLength = 75) {
  const value = String(text || "").trim();

  if (value.length <= maxLength) {
    return value;
  }

  return `${value.substring(0, maxLength - 3)}...`;
}

/*
 * ============================================================
 * BUILD PER-TICKET DETAIL TEXT
 * ============================================================
 *
 * Radio button option labels are short (75 char limit), so we
 * also render full details for each ticket above the radio
 * group, so the user can read title/priority/type/URL before
 * choosing.
 */

function buildTicketDetailBlock(ticket, index) {
  const lines = [
    `*${index + 1}. ${ticket.id} — ${ticket.title}*`,
    `Priority: ${ticket.priority || "No priority"}  |  Type: ${
      ticket.issueType || "N/A"
    }`,
  ];

  if (ticket.url) {
    lines.push(`<${ticket.url}|View in Notion>`);
  }

  return {
    type: "section",
    text: {
      type: "mrkdwn",
      text: lines.join("\n"),
    },
  };
}

/*
 * ============================================================
 * BUILD RADIO BUTTON OPTIONS
 * ============================================================
 */

/*
 * Slack rejects the whole message if any radio option label is longer
 * than 75 characters, so the title gets whatever room is left after the
 * "<priority> | <ID> | " prefix (which varies, e.g. "P1" vs "No priority").
 */
const MAX_RADIO_LABEL_LENGTH = 75;

function buildRadioLabel(ticket) {
  const prefix = `${ticket.priority || "No priority"} | ${ticket.id} | `;
  const titleRoom = Math.max(10, MAX_RADIO_LABEL_LENGTH - prefix.length);
  return getShortSlackText(
    `${prefix}${getShortSlackText(ticket.title, titleRoom)}`,
    MAX_RADIO_LABEL_LENGTH
  );
}

function buildRadioOptions(tickets) {
  return tickets.slice(0, MAX_RADIO_OPTIONS).map((ticket) => ({
    text: {
      type: "plain_text",
      text: buildRadioLabel(ticket),
      emoji: true,
    },
    value: GH_REPO_FULL
      ? `${ticket.id}|${GH_REPO_FULL}`
      : ticket.id,
  }));
}

/*
 * ============================================================
 * MAIN
 * ============================================================
 */

async function main() {
  try {
    console.log("🤖 Starting Notion → Slack approval flow...");

    // -----------------------------------------
    // 1. Load tickets generated by Notion script
    // -----------------------------------------

    // No ticket (no file, an empty list, or entries without an ID —
    // e.g. the `[ {} ]` placeholder committed to git) is a normal
    // outcome, not an error: log it, post nothing, finish successfully.
    const loadedTickets = fs.existsSync(TICKETS_FILE)
      ? JSON.parse(fs.readFileSync(TICKETS_FILE, "utf8"))
      : [];

    const tickets = (Array.isArray(loadedTickets) ? loadedTickets : []).filter(
      (ticket) => ticket && ticket.id
    );

    if (!tickets.length) {
      console.log("ℹ️ No ticket found. Nothing was sent to Slack.");
      return;
    }

    console.log(
      `📋 Loaded ${tickets.length} ticket(s) from Notion.`
    );

    tickets.forEach((ticket, index) => {
      console.log(
        `  [${index + 1}] ${ticket.id} | ${ticket.priority || "N/A"} | ${ticket.title}`
      );
    });

    if (tickets.length > MAX_RADIO_OPTIONS) {
      console.warn(
        `⚠️ ${tickets.length} tickets were loaded, but Slack radio_buttons ` +
        `only supports up to ${MAX_RADIO_OPTIONS}. Only the first ` +
        `${MAX_RADIO_OPTIONS} will be shown.`
      );
    }

    // -----------------------------------------
    // 2. Build Slack blocks
    // -----------------------------------------

    const blocks = [
      {
        type: "header",
        text: {
          type: "plain_text",
          text: "🤖 AI Automation Agent",
        },
      },

      {
        type: "section",
        text: {
          type: "mrkdwn",
          text:
            `*${tickets.length} completed Notion ticket${
              tickets.length === 1 ? "" : "s"
            } ready for automation:*`,
        },
      },

      {
        type: "divider",
      },
    ];

    // Full details for every ticket, so the user can read
    // before picking via the radio group below.

    tickets.forEach((ticket, index) => {
      blocks.push(buildTicketDetailBlock(ticket, index));
    });

    blocks.push({
      type: "divider",
    });

    blocks.push({
      type: "section",
      text: {
        type: "mrkdwn",
        text:
          "*Select ONE ticket to automate:*\n" +
          "_Only a single ticket can be chosen per run._",
      },
    });

    // -----------------------------------------
    // 3. Radio button selection (single-select)
    // -----------------------------------------

    blocks.push({
      type: "actions",
      block_id: "ticket_selection",
      elements: [
        {
          type: "radio_buttons",
          action_id: "selected_ticket",
          options: buildRadioOptions(tickets),
        },
      ],
    });

    // -----------------------------------------
    // 4. Approve button
    // -----------------------------------------

    blocks.push({
      type: "actions",
      block_id: "approve_ticket_action",
      elements: [
        {
          type: "button",
          text: {
            type: "plain_text",
            text: "Start Automation for Selected Ticket",
          },
          style: "primary",
          action_id: "approve_ticket",
          value: "approve",
        },
      ],
    });

    // -----------------------------------------
    // 5. Send Slack approval message
    // -----------------------------------------

    const response = await slack.chat.postMessage({
      channel: CHANNEL_ID,

      text: "AI Automation Agent - Select a ticket",

      blocks,
    });

    console.log("\n✅ Slack approval message created.");

    console.log(
      `Message TS: ${response.ts}`
    );

    console.log(
      `Tickets shown: ${tickets.length}`
    );

    console.log(
      "\n➡️ Waiting for the user to select one ticket and click " +
      "'Start Automation for Selected Ticket'."
    );

  } catch (error) {
    console.error(
      "\n❌ Failed to create Slack approval."
    );

    console.error(
      error.data?.error ||
      error.message ||
      error
    );

    if (error.data) {
      console.error(
        "\nSlack API response:"
      );

      console.error(
        JSON.stringify(error.data, null, 2)
      );
    }

    process.exit(1);
  }
}

main();